<#
.SYNOPSIS
    Scans a container image using Trivy and exports a machine-readable JSON vulnerability report.

.DESCRIPTION
    Automates container image vulnerability scanning for the Kubernetes Runtime Security Lab.
    Attempts execution via Windows native Trivy, WSL2 Trivy, or Docker container fallback.
    Validates the generated report is authentic and valid JSON.

.PARAMETER ImageName
    The container image to scan (defaults to "nginx:alpine").

.PARAMETER OutputPath
    Relative or absolute path for the generated JSON report (defaults to "reports/trivy-nginx-report.json").

.PARAMETER Scanners
    Trivy scanners to enable (defaults to "vuln,secret").

.EXAMPLE
    .\scripts\scan-images.ps1 -ImageName "nginx:alpine"
#>

[CmdletBinding()]
param (
    [string]$ImageName = "nginx:alpine",
    [string]$OutputPath = "reports/trivy-nginx-report.json",
    [string]$Scanners = "vuln,secret"
)

$ErrorActionPreference = "Stop"

Write-Host "==========================================================================" -ForegroundColor Cyan
Write-Host "         KUBERNETES RUNTIME SECURITY LAB - TRIVY IMAGE SCANNER            " -ForegroundColor Cyan
Write-Host "==========================================================================" -ForegroundColor Cyan

# Resolve output path
$resolvedOutputPath = [System.IO.Path]::GetFullPath($OutputPath)
$outputDir = [System.IO.Path]::GetDirectoryName($resolvedOutputPath)
if (-not (Test-Path $outputDir)) {
    New-Item -ItemType Directory -Path $outputDir -Force | Out-Null
}

Write-Host "[+] Target Image:      $ImageName" -ForegroundColor Yellow
Write-Host "[+] Destination File:  $resolvedOutputPath" -ForegroundColor Yellow
Write-Host "[+] Enabled Scanners: $Scanners" -ForegroundColor Yellow

# Detect Trivy Runtime
$scanSuccess = $false
$runtimeMethod = $null

# Option 1: Native Windows Trivy
if (Get-Command trivy -ErrorAction SilentlyContinue) {
    Write-Host "[+] Detected native Windows Trivy executable on PATH." -ForegroundColor Green
    $runtimeMethod = "Windows Native"
    try {
        & trivy image --format json --scanners $Scanners --output $resolvedOutputPath $ImageName
        if ($LASTEXITCODE -eq 0 -or (Test-Path $resolvedOutputPath)) { $scanSuccess = $true }
    } catch {
        Write-Warning "Native Trivy execution encountered an error: $_"
    }
}

# Option 2: WSL2 Trivy
if (-not $scanSuccess -and (Get-Command wsl -ErrorAction SilentlyContinue)) {
    Write-Host "[*] Checking for Trivy in WSL2 environment..." -ForegroundColor Cyan
    $wslCheck = wsl trivy --version 2>&1
    if ($LASTEXITCODE -eq 0) {
        Write-Host "[+] Detected Trivy inside WSL2." -ForegroundColor Green
        $runtimeMethod = "WSL2"
        
        # Convert Windows path (e.g. E:\foo\bar) to WSL path (/mnt/e/foo/bar)
        $drive = $resolvedOutputPath.Substring(0, 1).ToLower()
        $wslPath = "/mnt/$drive" + $resolvedOutputPath.Substring(2).Replace('\', '/')
        
        Write-Host "[*] Executing: wsl trivy image --format json --output '$wslPath' '$ImageName'" -ForegroundColor Gray
        wsl trivy image --format json --scanners $Scanners --output "$wslPath" "$ImageName"
        if (Test-Path $resolvedOutputPath) { $scanSuccess = $true }
    }
}

# Option 3: Docker container fallback
if (-not $scanSuccess -and (Get-Command docker -ErrorAction SilentlyContinue)) {
    Write-Host "[*] Attempting fallback via official Aquasec Docker container..." -ForegroundColor Cyan
    $runtimeMethod = "Docker Container"
    $dockerOutDir = $outputDir.Replace('\', '/')
    $fileName = [System.IO.Path]::GetFileName($resolvedOutputPath)
    
    # Mount local output directory into /reports
    docker run --rm -v "${dockerOutDir}:/reports" -v /var/run/docker.sock:/var/run/docker.sock aquasec/trivy:latest image --format json --scanners $Scanners -o "/reports/$fileName" $ImageName
    if (Test-Path $resolvedOutputPath) { $scanSuccess = $true }
}

if (-not (Test-Path $resolvedOutputPath)) {
    Write-Error "Scan failed: Report file '$resolvedOutputPath' was not generated by any available runtime."
    exit 1
}

# Validate JSON format
Write-Host "[+] Validating generated report format..." -ForegroundColor Cyan
try {
    $rawJson = Get-Content -Path $resolvedOutputPath -Raw -Encoding UTF8
    $parsedReport = $rawJson | ConvertFrom-Json
} catch {
    Write-Error "Report validation failed: Content in '$resolvedOutputPath' is not valid JSON. Error: $_"
    exit 1
}

# Summarize findings
$totalVulns = 0
$criticalCount = 0
$highCount = 0
$mediumCount = 0
$lowCount = 0
$findingsList = @()

if ($parsedReport.Results) {
    foreach ($result in $parsedReport.Results) {
        if ($result.Vulnerabilities) {
            foreach ($v in $result.Vulnerabilities) {
                $totalVulns++
                switch ($v.Severity) {
                    "CRITICAL" { $criticalCount++ }
                    "HIGH"     { $highCount++ }
                    "MEDIUM"   { $mediumCount++ }
                    "LOW"      { $lowCount++ }
                }
                $findingsList += [PSCustomObject]@{
                    ID       = $v.VulnerabilityID
                    Pkg      = $v.PkgName
                    Version  = $v.InstalledVersion
                    Severity = $v.Severity
                    Title    = $v.Title
                }
            }
        }
    }
}

Write-Host "==========================================================================" -ForegroundColor Green
Write-Host "                           SCAN SUMMARY RESULTS                           " -ForegroundColor Green
Write-Host "==========================================================================" -ForegroundColor Green
Write-Host "  Runtime Engine:       $runtimeMethod"
Write-Host "  Report File Size:     $((Get-Item $resolvedOutputPath).Length) bytes"
Write-Host "  Total Vulnerabilities: $totalVulns"
Write-Host "    - CRITICAL:         $criticalCount" -ForegroundColor Red
Write-Host "    - HIGH:             $highCount" -ForegroundColor Magenta
Write-Host "    - MEDIUM:           $mediumCount" -ForegroundColor Yellow
Write-Host "    - LOW:              $lowCount" -ForegroundColor Blue

if ($findingsList.Count -gt 0) {
    Write-Host "`nDiscovered Findings Breakdown:" -ForegroundColor Cyan
    $findingsList | Format-Table -AutoSize | Out-String | Write-Host
} else {
    Write-Host "`nNo vulnerabilities identified for image: $ImageName" -ForegroundColor Green
}

Write-Host "[+] Scan successfully completed. Report ready for DefectDojo import." -ForegroundColor Green
exit 0
